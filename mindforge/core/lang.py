def detect_language(text: str) -> str:
    """字符统计语种检测：zh / en / mixed。

    双显著判定：CJK ≥5% 且拉丁 ≥30% → mixed（两种文字实质共存）；
    否则 CJK ≥25% → zh；拉丁 ≥70% → en；低信息量兜底 mixed。
    空串/无字符返回 mixed（未知不假装确定）。
    """
    if not text:
        return "mixed"
    n = len(text)
    cjk = len(_RE_CJK.findall(text)) + len(_RE_CJK_EXT.findall(text))
    latin = len(_RE_LATIN.findall(text))
    cjk_r, latin_r = cjk / n, latin / n
    if cjk_r >= 0.05 and latin_r >= 0.30:
        return "mixed"
    if cjk_r >= _CJK_RATIO_ZH:
        return "zh"
    if latin_r >= _LATIN_RATIO_EN:
        return "en"
    return "mixed"


def normalize_cjk_variant(text: str) -> str:
    """繁→简高频字归一（查询侧用，不动存储内容）。

    简体文本原样返回（查表未命中逐字透传），繁体高频字折叠为对应
    简体——查询词与索引内容在同一变体空间上匹配。
    """
    if not text:
        return text
    return text.translate(str.maketrans(_S2T_TABLE))


def to_traditional_candidates(query: str) -> List[str]:
    """生成查询的繁体候选变体（简→繁方向反向查表）。

    FTS5 trigram 索引内容按写入原样分词：简体内容命简体 gram，繁体
    内容命繁体 gram。查询侧把「归一简体 + 繁体变体」双查（OR 并入）
    才能同时覆盖两种变体写入的语料。返回去重后的变体列表（含原文）。
    """
    if not query:
        return []
    simplified = normalize_cjk_variant(query)
    variants = [query]
    if simplified != query:
        variants.append(simplified)
    # 简转繁：反向表
    rev = {}
    for k, v in _TS_S_MAP.items():
        _s = v[0]
        for _ch in k:
            if _ch != _s and _s not in rev:
                rev[_s] = _ch
    trad = simplified.translate(str.maketrans(rev))
    if trad != simplified and trad not in variants:
        variants.append(trad)
    return variants


def cross_lang_anchor_terms(query: str, min_anchors: int = 1) -> List[str]:
    """跨语种锚点抽取：数字串与拉丁 token（形态跨语种不变）。

    「中文库 + 英文查询」时 query 里的数字/专名（v6.7.1 / Shanghai /
    2026-11-18）与中文内容中的同一形态字面相等——是零翻译条件下唯一
    可靠的召回锚。纯中文/纯英文查询（无锚点）返回空列表，调用方零改
    动直通。
    """
    if not query:
        return []
    anchors = []
    for m in _RE_ANCHOR.finditer(query):
        tok = m.group(0)
        # 跨语种可信形态 = 含数字的 token（v6.7.1 / 2026 / 42 号）。
        # 纯字母词（where / Shanghai）形态在中文语料中不可预期出现，
        # 无词典无法区分专名——诚实排除（边界见模块 docstring）。
        digits = len(_RE_DIGIT.findall(tok))
        letters = len(_RE_LATIN.findall(tok))
        if digits >= 1 and (digits >= 2 or letters >= 2):
            anchors.append(tok)
    return anchors
